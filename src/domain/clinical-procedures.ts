export const PROCEDURE_SLUGS = PROCEDURES.map((item) => item.slug);

/** 按 slug 取正文；未收录时返回 null，界面据此显示「本项暂无正文」而不是编造内容。 */
export function findProcedure(slug: string): ClinicalProcedure | null {
  return PROCEDURES.find((item) => item.slug === slug) ?? null;
}

/** 按分组取正文，用于页面分区渲染。 */
export function proceduresByGroup(group: ProcedureGroup): ClinicalProcedure[] {
  return PROCEDURES.filter((item) => item.group === group);
}

/** 穿刺类必须同时给出适应证与禁忌症，否则不能上界面（防止只讲操作不讲安全边界）。 */
export function isProcedureComplete(procedure: ClinicalProcedure): boolean {
  if (procedure.title.trim().length === 0 || procedure.summary.trim().length === 0) return false;
  if (procedure.steps.length === 0) return false;
  if (procedure.sources.length === 0) return false;
  if (procedure.pediatricNotes.length === 0) return false;
  if (procedure.complications.length === 0) return false;
  if (procedure.group === 'puncture') {
    return procedure.indications.length >= 3 && procedure.contraindications.length >= 3;
  }
  return procedure.preparation.length > 0;
}
